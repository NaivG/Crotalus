"""tools/light_oracle.py -- the independent ground truth for the light engine.

This file is **not** part of the engine. It is the ruler the engine is measured
with: a pure-Python translation of the rules in `LIGHT_PLAN.md` section 4
(which are Pumpkin's `pumpkin-world/src/lighting/engine.rs`, which in turn
follows vanilla's `LightEngine`). It deliberately imports nothing from
`world.light_engine` / `world.light_region` / `world.light_layout`, so a bug
shared between the kernel and its validator cannot hide here.

Speed is not a goal, clarity is -- but the rules turn out to be cheap: one
16x16x384 column of sky + block light takes about 25-45 ms here, against 0.7 ms
for the numba kernel the plan measured. The second algorithm in this file
(`max_field_reference`, ~0.7 s) exists only to cross-check the first.

Layout
------
A chunk volume is `(24, 4096)` -- `SECTIONS` sections of `CELLS_PER_SECTION`
cells. Section `j` holds world Y `MIN_Y + j*16 .. +15`, and cell
`y_local*256 + z*16 + x` inside it, which is exactly `ChunkSection.blocks`.
Flattened, one cell index is `(y - MIN_Y)*256 + z*16 + x`
(`chunk_cell`/`chunk_coords`). Light volumes use the same shape and are uint8.

Public API (stable -- `tools/check_light_engine.py` imports these)
------------------------------------------------------------------
Oracle core, all pure functions with no import-time work:

    relight_reference(blocks_vol, opacity_table, emitter_ids, emitter_levels, do_sky)
        -> (sky_vol, block_vol)          both (24, 4096) uint8
        Full sky + block light for one chunk. `neighbours={(dx, dz): volume}`
        (optional keyword) fills the 3x3 region around the centre chunk with
        real data; without it the chunk is lit as if its four sides were
        walls (see "Boundaries" below).

    relight_reference_region(blocks_region, opacity_table, emitter_ids,
                             emitter_levels, do_sky, valid=None)
        -> (sky_region, block_region)    both (9, 24, 4096) uint8
        The same core over a 3x3 region, `chunk_idx = (dz+1)*3 + (dx+1)`, i.e.
        the layout `LIGHT_PLAN.md` section 3 gives the numba kernel. Compare a
        kernel's output to this one index for index, with the same `valid`; a
        kernel that emits only the centre patch can be compared to
        `relight_reference` instead (single chunk, closed sides).

    region_surfaces(blocks_region, valid=None) -> (48, 48) int32
        The column heights the kernel's signature asks for, in the same
        region-local order: the highest **non-air** block's world Y.
    region_blocking_tops(blocks_region, opacity_table, valid=None) -> (48, 48)
        The other definition, and the one the kernel's own `_column_top` uses:
        the highest cell with `opacity > 0`, as region-relative ry (-1 = none).
    chunk_index(dx, dz) -> int            region slot of a chunk offset

    increase_reference(light_vol, blocks_vol, seeds, opacity_table, do_sky=True)
        -> light_vol                     (24, 4096) uint8
        Vanilla's increase BFS from `seeds` (flat indices).

    decrease_reference(light_vol, blocks_vol, seeds, opacity_table, do_sky=False)
        -> light_vol                     (24, 4096) uint8
        Vanilla's decrease pass, then the increase it triggers. `seeds` are
        `(flat_index, old_level)` pairs; each seeded cell is cleared first
        (LIGHT_PLAN section 9.1 pit 2). This is the second ruler for the
        "increment == full" assertion.

    incremental_reference(sky_vol, block_vol, old_blocks, new_blocks,
                          opacity_table, emitter_ids, emitter_levels, do_sky)
        -> (sky_vol, block_vol)
        LIGHT_PLAN section 4.6's four queues in pure Python: a block change is
        applied to an already-lit chunk and the result must equal
        `relight_reference(new_blocks, ...)` cell for cell.

    column_fill_reference(blocks_vol, opacity_table) -> sky_vol
        Stage 1 alone (no lateral seeds, no BFS) -- the no-flood-fill baseline
        section 5.2 rows against.
    max_field_reference(blocks_vol, opacity_table, emitter_ids,
                        emitter_levels, do_sky) -> (sky_vol, block_vol)
        The same rules as an order-independent max-field relaxation (heap,
        no seeds, no queue order): a second algorithm for the same rules, to
        check the bookkeeping of the BFS above.

Tables (the oracle reads `registry/entries.py` itself, never the engine's
`registry.blocks.light_*` helpers, for the same independence reason):

    registry_opacity_table()  -> uint8[65536]
    registry_emitter_tables() -> (int32[E], uint8[E])

Real-chunk fixture (cached under `FIXTURE_CACHE`, generated by `world.legacy`):

    build_base_volume(force=False)   -> (24, 4096) uint16
    build_region_volumes(force=False) -> (9, 24, 4096) uint16, nine *real*
                                        neighbours at `chunk_index(dx, dz)`
    fixture_scenes(force=False)      -> {name: (blocks, info)} for "base",
                                        "shafts", "sealed_cave_torch",
                                        "water_column"
    make_shafts / make_sealed_cave / make_water_column

Synthetic semantic scenes:

    semantic_scenes() -> {name: (volume, info)}
    scene_solid_roof / scene_water_column / scene_down_shaft /
    scene_glass_roof / scene_torch_in_water / scene_sealed_torch_cave

Rules implemented (LIGHT_PLAN sections 4.2-4.6)
-----------------------------------------------
* `new_level = level - max(opacity, 1)`, where opacity is the *entered* cell's
  (0/1/15 -- see section 1.1: this data has exactly those three values).
* Sky, and only sky: `level == 15 and direction is down and opacity == 0 -> 15`.
* Sky stage 1, per column: everything above the column's highest non-air block
  is 15; from that block down `light -= opacity` (no `max(`, no down special),
  saturating at 0, stopping when it reaches 0.
* Sky stage 2, lateral seeds: scan from `max(own top, four neighbour tops)` down
  to `MIN_Y`; queue a cell whose own top is not above it (`y == top`) or that
  sits below some neighbour's top -- this is the only way light enters a cave
  mouth or a shaft from the side.
* Stages 2 and 3 of both engines: a plain BFS that re-queues on increase. No
  visited set: the value written is always the maximum over paths, so the
  result does not depend on queue order (a kernel that dedupes instead produces
  the same numbers unless it is darker than vanilla).

Boundaries
----------
A single chunk is lit with walls on its four sides: light cannot enter from an
unloaded neighbour, which is what `LIGHT_PLAN.md` section 4.5 requires (a patch
that is missing a neighbour is not run at all). Numbers measured in the plan,
and the fixture statistics, come from single-chunk runs. Pass `neighbours=...`
for the exact 3x3 answer.

Two measured footnotes (both re-checkable from `main()`)
--------------------------------------------------------
* **The sky's down special changes nothing a fixture can see.** Removing
  `level == 15 and down and opacity == 0 -> 15` from both the increase and the
  decrease leaves all four real-chunk scenes and all five semantic ones
  cell-for-cell identical (0 cells differ in sky and block light, in the full
  relight and in the incremental path). Stage 1 already gives 15 to an
  opacity-0 run below the highest non-air block, and the incremental path's
  column rescan clears the whole affected chain before propagating, so the
  special never gets to decide anything. It only shows when a decrease is
  seeded *partially*: then it is what keeps a downward chain going
  (LIGHT_PLAN section 9.1 pit 3), which is a property of the kernel's
  `update_sky_column` and not of any static scene. It is implemented here
  because Pumpkin and vanilla both have it.
* **LIGHT_PLAN section 5.2's two rows are the shafted column.** The unshafted
  column is 65,360 lit / 28 middle, so 66,082 is not the unshafted number.
  With `SHAFT_SPECS` (section 5.2's two shafts, whose positions the plan does
  not record) the engine gives 66,079 / 691 and 65,388 cells at 15 -- the
  published engine row within 3 cells, and the published first row's 65,388
  exactly. Stage 1 alone on that shafted column gives 65,416 lit / 28 middle /
  65,388 at 15, so the plan's first row is a no-flood-fill field of the
  *shafted* column; the codec's own `y >= top + 2` rule gives 65,128 lit and 0
  middle there. `SHAFT_SPECS` is a sweep-based recovery of the shafts, and
  `main()` prints both scenarios side by side.

Run: py -3.14t tools/light_oracle.py
"""

