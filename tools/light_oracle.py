def _relight_region_core(
    blocks_region: np.ndarray,
    opacity_table: np.ndarray,
    lum_table: np.ndarray,
    valid: np.ndarray,
    do_sky: bool,
) -> Tuple[bytearray, bytearray]:
    """Sky + block light for a 3x3 region, as raw region buffers."""
    op, nonair = _load_region(blocks_region, opacity_table, valid)
    sky = bytearray(_REGION_CELLS)
    block = bytearray(_REGION_CELLS)

    if do_sky:
        tops = _region_tops(nonair, valid)
        _sky_fill(sky, op, tops, valid)
        queue: deque = deque()
        _sky_seed(sky, tops, valid, queue)
    else:
        queue = deque()

    block_queue: deque = deque()
    _block_seed(block, blocks_region, lum_table, valid, block_queue)
    _increase(block, op, block_queue, is_sky=False)

    if do_sky:
        _increase(sky, op, queue, is_sky=True)
    return sky, block


def _emitter_lum_table(emitter_ids, emitter_levels) -> np.ndarray:
    """`(state ids, levels)` -> `uint8[65536]` luminance per state."""
    table = np.zeros(65536, dtype=np.uint8)
    ids = np.asarray(emitter_ids, dtype=np.int64).reshape(-1)
    levels = np.asarray(emitter_levels, dtype=np.uint8).reshape(-1)
    if ids.size != levels.size:
        raise ValueError(f"emitter tables differ in length: {ids.size} vs {levels.size}")
    table[ids] = levels
    return table


def relight_reference(
    blocks_vol: np.ndarray,
    opacity_table: np.ndarray,
    emitter_ids,
    emitter_levels,
    do_sky: bool,
    neighbours: Optional[Dict[Tuple[int, int], np.ndarray]] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """Full sky + block light for one chunk: `(sky_vol, block_vol)`, uint8.

    `neighbours` maps `(dx, dz)` in `{-1, 0, 1}**2` (excluding the centre) to a
    `(24, 4096)` block volume, and fills the 3x3 region the engine works on.
    Without it the chunk is lit with walls on its sides.
    """
    region = np.zeros((9, SECTIONS, CELLS_PER_SECTION), dtype=np.uint16)
    valid = _CENTER_VALID.copy()
    region[_CENTER_CHUNK] = np.asarray(blocks_vol, dtype=np.uint16).reshape(
        SECTIONS, CELLS_PER_SECTION)
    for (dx, dz), volume in (neighbours or {}).items():
        if dx not in (-1, 0, 1) or dz not in (-1, 0, 1) or (dx == 0 and dz == 0):
            raise ValueError(f"neighbour offset {(dx, dz)} is not part of the 3x3 ring")
        ci = _chunk_index(dx, dz)
        region[ci] = np.asarray(volume, dtype=np.uint16).reshape(
            SECTIONS, CELLS_PER_SECTION)
        valid[ci] = True

    lum_table = _emitter_lum_table(emitter_ids, emitter_levels)
    sky, block = _relight_region_core(region, opacity_table, lum_table, valid, do_sky)
    return _extract_chunk(sky), _extract_chunk(block)


def relight_reference_region(
    blocks_region: np.ndarray,
    opacity_table: np.ndarray,
    emitter_ids,
    emitter_levels,
    do_sky: bool,
    valid: Optional[Sequence[bool]] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """Sky + block light for a whole 3x3 region: two `(9, 24, 4096)` uint8 arrays.

    `blocks_region` uses the kernel's layout, `chunk_idx = (dz+1)*3 + (dx+1)`.
    `valid` marks which of the nine chunks exist; absent ones stay dark and
    block light.
    """
    region = np.asarray(blocks_region, dtype=np.uint16).reshape(
        9, SECTIONS, CELLS_PER_SECTION)
    mask = np.ones(9, dtype=bool) if valid is None else np.asarray(valid, dtype=bool)
    lum_table = _emitter_lum_table(emitter_ids, emitter_levels)
    sky, block = _relight_region_core(region, opacity_table, lum_table, mask, do_sky)

    sky_out = np.zeros((9, SECTIONS, CELLS_PER_SECTION), dtype=np.uint8)
    block_out = np.zeros((9, SECTIONS, CELLS_PER_SECTION), dtype=np.uint8)
    for ci in range(9):
        if not mask[ci]:
            continue
        dx, dz = ci % 3 - 1, ci // 3 - 1
        sky_out[ci] = _extract_chunk(sky, dx, dz)
        block_out[ci] = _extract_chunk(block, dx, dz)
    return sky_out, block_out


def _region_index_for(flat_index: int) -> int:
    """Flat `(24, 4096)` index of the centre chunk -> region buffer index."""
    return _local_padded(*chunk_coords(int(flat_index)))


def increase_reference(
    light_vol: np.ndarray,
    blocks_vol: np.ndarray,
    seeds: Iterable[int],
    opacity_table: np.ndarray,
    do_sky: bool = True,
) -> np.ndarray:
    """Vanilla's increase BFS from `seeds`, one chunk, walls on the sides."""
    region = np.zeros((9, SECTIONS, CELLS_PER_SECTION), dtype=np.uint16)
    region[_CENTER_CHUNK] = np.asarray(blocks_vol, dtype=np.uint16).reshape(
        SECTIONS, CELLS_PER_SECTION)
    op, _nonair = _load_region(region, opacity_table, _CENTER_VALID)
    light = _load_light(light_vol)
    queue = deque(_region_index_for(seed) for seed in seeds)
    _increase(light, op, queue, do_sky)
    return _extract_chunk(light)


def decrease_reference(
    light_vol: np.ndarray,
    blocks_vol: np.ndarray,
    seeds: Iterable[Tuple[int, int]],
    opacity_table: np.ndarray,
    do_sky: bool = False,
) -> np.ndarray:
    """Vanilla's decrease pass, then the increase it triggers.

    `light_vol` is not modified; the new volume is returned. `seeds` are
    `(flat_index, old_level)` pairs -- the cells whose light was just removed.
    Each seeded cell is cleared to 0 before its neighbours are judged.
    """
    region = np.zeros((9, SECTIONS, CELLS_PER_SECTION), dtype=np.uint16)
    region[_CENTER_CHUNK] = np.asarray(blocks_vol, dtype=np.uint16).reshape(
        SECTIONS, CELLS_PER_SECTION)
    op, _nonair = _load_region(region, opacity_table, _CENTER_VALID)
    light = _load_light(light_vol)

    cleared: List[Tuple[int, int]] = []
    for index, old in seeds:
        idx = _region_index_for(index)
        cleared.append((idx, int(old)))
        light[idx] = 0

    increase: deque = deque()
    if cleared:
        _decrease(light, op, cleared, do_sky, increase)
    if increase:
        _increase(light, op, increase, do_sky)
    return _extract_chunk(light)


def column_fill_reference(
    blocks_vol: np.ndarray,
    opacity_table: np.ndarray,
) -> np.ndarray:
    """Stage 1 alone: the sky light a column has from its own column, no BFS.

    This is the "no flood fill" baseline section 5.2 compares the engine
    against (the codec's own approximation is a coarser `y >= top + 2` rule,
    which is why it lights a different set -- see the module docstring).
    """
    volume = np.asarray(blocks_vol, dtype=np.uint16).reshape(
        SECTIONS, CELLS_PER_SECTION)
    region = np.zeros((9, SECTIONS, CELLS_PER_SECTION), dtype=np.uint16)
    region[_CENTER_CHUNK] = volume
    op, nonair = _load_region(region, opacity_table, _CENTER_VALID)
    sky = bytearray(_REGION_CELLS)
    _sky_fill(sky, op, _region_tops(nonair, _CENTER_VALID), _CENTER_VALID)
    return _extract_chunk(sky)


def max_field_reference(
    blocks_vol: np.ndarray,
    opacity_table: np.ndarray,
    emitter_ids,
    emitter_levels,
    do_sky: bool = True,
) -> Tuple[np.ndarray, np.ndarray]:
    """The same rules as an order-independent max-field relaxation.

    A second algorithm for the same transfer rules: every lit cell (or emitter)
    is a source, cells are settled brightest first out of a heap, and a
    neighbour is relaxed only when it can be raised. `relight_reference` is a
    FIFO BFS over the plan's seed sets; this one has no seed set and no queue
    order, so agreement between the two says the *bookkeeping* is right while
    the semantic scenes say the *rules* are.
    """
    op_table = np.asarray(opacity_table, dtype=np.uint8)
    lum_table = _emitter_lum_table(emitter_ids, emitter_levels)
    states = np.asarray(blocks_vol, dtype=np.uint16).reshape(-1)
    op = np.asarray(op_table[states], dtype=np.uint8)
    block = np.asarray(lum_table[states], dtype=np.uint8).copy()
    if do_sky:
        sky = np.asarray(column_fill_reference(blocks_vol, op_table),
                         dtype=np.uint8).reshape(-1).copy()
    else:
        sky = np.zeros(states.size, dtype=np.uint8)

    for light, is_sky in ((block, False), (sky, True)):
        _relax_to_fixed_point(light, op, is_sky)
    return sky.reshape(SECTIONS, CELLS_PER_SECTION), block.reshape(
        SECTIONS, CELLS_PER_SECTION)


def _relax_to_fixed_point(light: np.ndarray, op: np.ndarray, is_sky: bool) -> None:
    """Settle every lit cell brightest-first, relaxing its six neighbours."""
    heap = [(-int(level), int(index))
            for index, level in enumerate(light) if level > 1]
    heapq.heapify(heap)
    while heap:
        negative, index = heapq.heappop(heap)
        level = int(light[index])
        if level != -negative:
            continue                      # stale entry, the cell rose since
        x = index % 16
        z = (index // 16) % 16
        y = index // 256
        for delta, inside in (
            (1, x < 15), (-1, x > 0),
            (16, z < 15), (-16, z > 0),
            (256, y < HEIGHT - 1), (-256, y > 0),
        ):
            if not inside:
                continue
            n = index + delta
            nop = int(op[n])
            if nop == 0 and is_sky and level == 15 and delta == -256:
                new = 15
            elif nop <= 1:
                new = level - 1
            else:
                new = level - nop
            if new > light[n]:
                light[n] = new
                if new > 1:
                    heapq.heappush(heap, (-new, n))


def _rescan_column(
    sky: bytearray,
    op: bytearray,
    nonair: bytearray,
    x: int,
    z: int,
    decrease: List[Tuple[int, int]],
    increase: deque,
) -> None:
    """`update_sky_column` (section 4.6): re-run stage 1 for one column.

    Cells that got darker are cleared and seeded into the decrease queue; cells
    that got brighter are seeded into the increase queue.
    """
    idx = _local_padded(x, MAX_Y - 1, z)
    top = MIN_Y - 1
    for py in range(HEIGHT - 1, -1, -1):
        if nonair[idx]:
            top = MIN_Y + py
            break
        idx -= _STEP_Y

    base = _local_padded(x, MIN_Y, z)
    fresh: Dict[int, int] = {}
    light = 15
    idx = base + (top - MIN_Y) * _STEP_Y
    for wy in range(top, MIN_Y - 1, -1):
        light -= op[idx]
        if light < 0:
            light = 0
        fresh[wy] = light
        if light == 0:
            break
        idx -= _STEP_Y
    for wy in range(top + 1, MAX_Y):
        fresh[wy] = 15

    for wy in range(MIN_Y, MAX_Y):
        idx = base + (wy - MIN_Y) * _STEP_Y
        current = sky[idx]
        new = fresh.get(wy, 0)
        if new == current:
            continue
        if new > current:
            sky[idx] = new
            increase.append(idx)
        else:
            sky[idx] = 0
            decrease.append((idx, current))


def incremental_reference(
    sky_vol: np.ndarray,
    block_vol: np.ndarray,
    old_blocks: np.ndarray,
    new_blocks: np.ndarray,
    opacity_table: np.ndarray,
    emitter_ids,
    emitter_levels,
    do_sky: bool = True,
) -> Tuple[np.ndarray, np.ndarray]:
    """Section 4.6's incremental path, from an already-lit chunk.

    The result must equal `relight_reference(new_blocks, ...)`: that equality is
    the assertion this function exists to make checkable without the engine.
    """
    op_table = np.asarray(opacity_table, dtype=np.uint8)
    lum_table = _emitter_lum_table(emitter_ids, emitter_levels)
    old_flat = np.asarray(old_blocks, dtype=np.uint16).reshape(-1)
    new_flat = np.asarray(new_blocks, dtype=np.uint16).reshape(-1)
    changed = np.flatnonzero(old_flat != new_flat)

    region = np.zeros((9, SECTIONS, CELLS_PER_SECTION), dtype=np.uint16)
    region[_CENTER_CHUNK] = new_flat.reshape(SECTIONS, CELLS_PER_SECTION)
    op, nonair = _load_region(region, op_table, _CENTER_VALID)
    sky = _load_light(sky_vol)
    block = _load_light(block_vol)

    block_decrease: List[Tuple[int, int]] = []
    block_increase: deque = deque()
    sky_decrease: List[Tuple[int, int]] = []
    sky_increase: deque = deque()
    columns = set()

    for i in changed:
        x, y, z = chunk_coords(int(i))
        idx = _local_padded(x, y, z)
        old_state, new_state = int(old_flat[i]), int(new_flat[i])
        old_op, new_op = int(op_table[old_state]), int(op_table[new_state])
        old_lum, new_lum = int(lum_table[old_state]), int(lum_table[new_state])
        if old_op == new_op and old_lum == new_lum:
            continue                      # step 2: light cannot have changed

        # A cell that just became opaque cannot hold light; and if it just
        # became transparent, its neighbours may now reach further into it.
        if new_op > old_op and block[idx] > 0:
            block_decrease.append((idx, block[idx]))
            block[idx] = 0
        if new_lum > old_lum:
            block[idx] = new_lum
            block_increase.append(idx)
        elif new_lum < old_lum and block[idx] > 0:
            block_decrease.append((idx, block[idx]))
            block[idx] = 0
        damp = 1 if new_op <= 1 else 15
        for delta in _DIRECTIONS:
            n = idx + delta
            if block[n] > 0 and block[n] - damp > block[idx]:
                block_increase.append(n)

        # Step 4: this (x, z) column is recomputed, vertically, from scratch.
        columns.add((x, z))

    if do_sky:
        for x, z in sorted(columns):
            _rescan_column(sky, op, nonair, x, z, sky_decrease, sky_increase)

    if block_decrease:
        _decrease(block, op, block_decrease, is_sky=False, increase=block_increase)
    if block_increase:
        _increase(block, op, block_increase, is_sky=False)
    if sky_decrease:
        _decrease(sky, op, sky_decrease, is_sky=True, increase=sky_increase)
    if sky_increase:
        _increase(sky, op, sky_increase, is_sky=True)

    return _extract_chunk(sky), _extract_chunk(block)


