def volume_digest(volume: np.ndarray) -> str:
    """SHA-256 of a block volume, so two runs can be shown to share a fixture."""
    return hashlib.sha256(np.ascontiguousarray(
        np.asarray(volume, dtype=np.uint16)).tobytes()).hexdigest()


def block_composition(volume: np.ndarray, opacity_table: np.ndarray,
                      water: int, lava: int) -> Dict[str, int]:
    """Air / water / lava / everything else -- section 5.4's taxonomy.

    The plan's "opaque 30,775" is `total - air - water - lava`, not
    `opacity == 15`: this fixture also holds 31 opacity-1 and 7 opacity-0
    non-air cells (leaves, plants), and the 27 water cells are opacity 1.
    """
    states = np.asarray(volume, dtype=np.uint16).reshape(-1)
    op = np.asarray(opacity_table, dtype=np.uint8)[states]
    return {
        "air": int((states == AIR).sum()),
        "water": int((states == water).sum()),
        "lava": int((states == lava).sum()),
        "opaque": int(states.size - (states == AIR).sum()
                      - (states == water).sum() - (states == lava).sum()),
        "opacity_15": int((op == 15).sum()),
        "opacity_1": int((op == 1).sum()),
        "opacity_0_non_air": int(((op == 0) & (states != AIR)).sum()),
    }


def light_statistics(sky: np.ndarray, block: np.ndarray) -> Dict[str, int]:
    """Lit-cell counts in the plan's terms."""
    sky_flat = np.asarray(sky, dtype=np.uint8).reshape(-1)
    block_flat = np.asarray(block, dtype=np.uint8).reshape(-1)
    return {
        "sky_lit": int((sky_flat > 0).sum()),
        "sky_middle": int(((sky_flat > 0) & (sky_flat < 15)).sum()),
        "sky_full": int((sky_flat == 15).sum()),
        "block_lit": int((block_flat > 0).sum()),
        "any_lit": int(((sky_flat > 0) | (block_flat > 0)).sum()),
    }


