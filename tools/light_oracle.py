def _scene_volume() -> np.ndarray:
    """An all-air chunk volume."""
    return np.zeros((SECTIONS, CELLS_PER_SECTION), dtype=np.uint16)


def _stone(registry=None) -> int:
    from world.block_states import default_state_id
    return default_state_id("minecraft:stone")


def _state(name: str, properties: Optional[Dict[str, object]] = None) -> int:
    from world.block_states import state_id
    return state_id(name, properties)


def _fill_box(volume, x0, y0, z0, x1, y1, z1, state) -> None:
    for y in range(y0, y1 + 1):
        for z in range(z0, z1 + 1):
            for x in range(x0, x1 + 1):
                set_state(volume, x, y, z, state)


def scene_solid_roof() -> Tuple[np.ndarray, Dict[str, int]]:
    """A slab over open ground: nothing below it sees the sky.

    Probe: `sky(x, roof_y - 1, z) == 0`, and `sky(x, roof_y + 1, z) == 15`.
    """
    volume = _scene_volume()
    stone = _stone()
    floor_y, roof_y = -60, -40
    _fill_box(volume, 0, MIN_Y, 0, 15, floor_y, 15, stone)
    _fill_box(volume, 0, roof_y, 0, 15, roof_y, 15, stone)
