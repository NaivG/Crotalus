#: `world.legacy` + `seed=1234` + chunk `(0, 0)` is the column section 5.4
#: measured: air 67,499 / water 27 / lava 3 -- a normal overworld surface
#: column with a small pond and a little cave lava.
FIXTURE_SEED = 1234
FIXTURE_CHUNK = (0, 0)
FIXTURE_BACKEND = "legacy"
FIXTURE_CACHE = (Path(tempfile.gettempdir()) / "crotalus_light_oracle"
                 / f"legacy_seed{FIXTURE_SEED}_chunk{FIXTURE_CHUNK[0]}"
                   f"_{FIXTURE_CHUNK[1]}.npz")

#: The two shafts of section 5.2: `(x, z, depth)`, each dug from that column's
#: own surface downwards. The plan does not record where they were, so these
#: are a **recovery**: every column was swept for both depths and this pair is
#: the one that best reproduces the published engine row (66,079/691 against
#: the plan's 66,082/694, with the same 65,388 cells at 15). Section 5.2's
#: numbers belong to this shafted column, not to the unshafted one -- `main()`
#: prints both so the attribution is checkable rather than assumed.
SHAFT_SPECS: Tuple[Tuple[int, int, int], ...] = ((4, 4, 30), (5, 7, 17))


def generate_base_volume(
    seed: int = FIXTURE_SEED,
    chunk_pos: Tuple[int, int] = FIXTURE_CHUNK,
) -> np.ndarray:
    """Generate one real chunk with the `world.legacy` backend (~1.6 s).

    Uses the backend and the generator defaults as they are: no heightmap is
    stripped and nothing is re-dressed, because the plan's numbers came from
    `generate_chunk`'s full output.
    """
    from registry import init_registries
    from world.chunk import Chunk, ChunkPos
    from world.generator import GeneratorSettings, GeneratorType
    from world.legacy.generator import LegacyWorldGenerator

    init_registries(log_summary=False)
    generator = LegacyWorldGenerator(GeneratorSettings(
        generator_type=GeneratorType.NORMAL, seed=seed, preset="overworld"))
    chunk = Chunk(position=ChunkPos(*chunk_pos), min_y=MIN_Y, height=HEIGHT)
    generator.generate_chunk(chunk)
    return chunk.blocks_view().reshape(SECTIONS, CELLS_PER_SECTION).astype(np.uint16)


def _load_fixture_cache() -> Dict[str, np.ndarray]:
    """Everything cached so far, keyed by npz array name. Empty when absent."""
    if not FIXTURE_CACHE.exists():
        return {}
    with np.load(FIXTURE_CACHE) as data:
        return {name: data[name] for name in data.files}


def _save_fixture_cache(arrays: Dict[str, np.ndarray]) -> None:
    """Rewrite the cache with `arrays` (np.savez replaces the file)."""
    payload = {name: value for name, value in arrays.items()
               if name not in ("seed", "chunk_x", "chunk_z")}
    FIXTURE_CACHE.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(FIXTURE_CACHE, seed=FIXTURE_SEED,
                        chunk_x=FIXTURE_CHUNK[0], chunk_z=FIXTURE_CHUNK[1],
                        **payload)


def build_base_volume(force: bool = False) -> np.ndarray:
    """The fixture's untouched column, from the cache or freshly generated."""
    cache = {} if force else _load_fixture_cache()
    volume = cache.get("blocks")
    if volume is not None and volume.shape == (SECTIONS, CELLS_PER_SECTION):
        return volume.astype(np.uint16)
    volume = generate_base_volume()
    cache["blocks"] = volume
    _save_fixture_cache(cache)
    return volume


def build_region_volumes(force: bool = False) -> np.ndarray:
    """The **nine real** chunks around the fixture centre, `(9, 24, 4096)` uint16.

    Chunk `(dx, dz)` is `world.legacy` seed 1234 at world chunk
    `(FIXTURE_CHUNK[0] + dx, FIXTURE_CHUNK[1] + dz)`, stored at
    `chunk_index(dx, dz)`. Real neighbours, not copies of the centre: cliffs and
    caves that cross a chunk border are the only way to test that a patch gets
    its border right (`LIGHT_PLAN.md` section 5.5 lists this as unmeasured).

    Cached next to the base column; the first build is nine generations.
    """
    cache = {} if force else _load_fixture_cache()
    region = cache.get("region")
    if region is not None and region.shape == (9, SECTIONS, CELLS_PER_SECTION):
        return region.astype(np.uint16)

    region = np.zeros((9, SECTIONS, CELLS_PER_SECTION), dtype=np.uint16)
    centre = cache.get("blocks")
    if centre is None or centre.shape != (SECTIONS, CELLS_PER_SECTION):
        centre = generate_base_volume()
        cache["blocks"] = centre
    for dz in (-1, 0, 1):
        for dx in (-1, 0, 1):
            if dx == 0 and dz == 0:
                volume = centre
            else:
                volume = generate_base_volume(
                    chunk_pos=(FIXTURE_CHUNK[0] + dx, FIXTURE_CHUNK[1] + dz))
            region[_chunk_index(dx, dz)] = volume
    cache["region"] = region
    _save_fixture_cache(cache)
    return region


def make_shafts(
    volume: np.ndarray,
    specs: Sequence[Tuple[int, int, int]] = SHAFT_SPECS,
) -> Tuple[np.ndarray, List[Tuple[int, int, int, int]]]:
    """Dig 1x1 shafts down from each column's surface.

    Returns `(volume, dug)` where `dug` is `(x, z, top_y, bottom_y)` per shaft.
    A 1x1 air shaft is lit 15 to its bottom by stage 1; its only visible effect
    is the light it lets into whatever it breaks into.
    """
    out = volume.copy()
    dug: List[Tuple[int, int, int, int]] = []
    for x, z, depth in specs:
        top = column_top(out, x, z)
        for y in range(top, top - depth, -1):
            set_state(out, x, y, z, AIR)
        dug.append((x, z, top, top - depth + 1))
    return out, dug


def make_cave_torch_state() -> Tuple[int, int]:
    """`(stone, torch)` state ids, for the cave scenario."""
    return _stone(), _state("minecraft:torch")


def make_sealed_cave(
    volume: np.ndarray,
    room: Tuple[int, int, int] = (11, 7, 11),
) -> Tuple[np.ndarray, Dict[str, int]]:
    """Carve a sealed room out of solid stone and light it with one torch.

    The room is only placed where a shell two blocks thick is opaque stone in
    the untouched chunk, so "the cave has no sky light" is a property of the
    scene and not of where the carver happened to put a tunnel.
    """
    stone, torch = make_cave_torch_state()
    rx, ry, rz = room
    shell = 2
    width, height, depth = rx + 2 * shell, ry + 2 * shell, rz + 2 * shell
    out = volume.copy()

    found = None
    for y0 in range(MIN_Y + 8, 200):
        for z0 in range(0, 16 - depth + 1):
            for x0 in range(0, 16 - width + 1):
                if _box_is_solid(out, x0, y0, z0, width, height, depth):
                    found = (x0, y0, z0)
                    break
            if found:
                break
        if found:
            break
    if found is None:
        raise RuntimeError("no solid box for the sealed cave in this fixture")

    x0, y0, z0 = found
    _fill_box(out, x0, y0, z0, x0 + width - 1, y0 + height - 1, z0 + depth - 1, AIR)
    _fill_box(out, x0 + shell - 1, y0 + shell - 1, z0 + shell - 1,
              x0 + width - shell, y0 + height - shell, z0 + depth - shell, stone)
    interior_x0, interior_y0, interior_z0 = x0 + shell, y0 + shell, z0 + shell
    interior_x1 = interior_x0 + rx - 1
    interior_y1 = interior_y0 + ry - 1
    interior_z1 = interior_z0 + rz - 1
    _fill_box(out, interior_x0, interior_y0, interior_z0,
              interior_x1, interior_y1, interior_z1, AIR)

    tx = (interior_x0 + interior_x1) // 2
    tz = (interior_z0 + interior_z1) // 2
    set_state(out, tx, interior_y0, tz, torch)
    return out, {"torch_x": tx, "torch_y": interior_y0, "torch_z": tz,
                 "x0": interior_x0, "y0": interior_y0, "z0": interior_z0,
                 "x1": interior_x1, "y1": interior_y1, "z1": interior_z1}


def _box_is_solid(volume: np.ndarray, x0: int, y0: int, z0: int,
                  width: int, height: int, depth: int) -> bool:
    flat = volume.reshape(-1)
    for y in range(y0, y0 + height):
        for z in range(z0, z0 + depth):
            row = chunk_cell(x0, y, z)
            for x in range(width):
                if flat[row + x] == AIR:
                    return False
    return True


def make_water_column(
    volume: np.ndarray,
    depth: int = 8,
) -> Tuple[np.ndarray, Dict[str, int]]:
    """Dig a sealed well into the terrain and fill it with water.

    The well's four walls are forced to stone for its whole depth, so `15 - n`
    is exact: the only way in is the well's own open top.
    """
    water = _state("minecraft:water")
    stone = _stone()
    out = volume.copy()
    for x in range(1, 15):
        for z in range(1, 15):
            top = column_top(out, x, z)
            if top < MIN_Y + depth + 2:
                continue
            if get_state(out, x, top - depth, z) == AIR:
                continue                      # needs a floor to sit on
            for y in range(top - depth, top + 1):
                for dx, dz in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                    set_state(out, x + dx, y, z + dz, stone)
            for y in range(top - depth + 1, top + 1):
                set_state(out, x, y, z, water)
            return out, {"x": x, "z": z, "top": top, "depth": depth}
    raise RuntimeError("no sealed water column site in this fixture")


def fixture_scenes(force: bool = False) -> Dict[str, Tuple[np.ndarray, Dict]]:
    """The four real-chunk scenes, `{name: (blocks, info)}`.

    `base`               the untouched column (section 5.4)
    `shafts`             `base` with two shafts punched (section 5.2)
    `sealed_cave_torch`  `base` with a sealed room and one torch in it
    `water_column`       `base` with a sealed, water-filled well

    Rooms and wells are carved into copies; `base` itself is never modified.
    `info` holds the coordinates the scene's assertions need (shaft ranges,
    room bounds and torch position, well position).
    """
    base = build_base_volume(force=force)
    shafts, dug = make_shafts(base)
    cave, room = make_sealed_cave(base)
    water, column = make_water_column(base)
    return {
        "base": (base, {}),
        "shafts": (shafts, {"dug": dug}),
        "sealed_cave_torch": (cave, room),
        "water_column": (water, column),
    }


