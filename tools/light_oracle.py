    emitter_ids, emitter_levels = registry_emitter_tables()
    total_states = _registry_blocks().total_states
    distribution = {
        value: int((opacity_table[:total_states] == value).sum())
        for value in (0, 1, 15)
    }
    print(f"  opacity table over {total_states} states: {distribution}, "
          f"{emitter_ids.size} emitting states")
    checks.check("planned opacity distribution {0: 16240, 1: 10872, 15: 2559}",
                 distribution == {0: 16240, 1: 10872, 15: 2559},
                 f"got {distribution}")

    composition = block_composition(base, opacity_table, BLOCKS.WATER, BLOCKS.LAVA)
    print("  block composition: " + ", ".join(
        f"{key} {value}" for key, value in composition.items()))
    for key, want in PLAN_COMPOSITION.items():
        got = composition[key]
        checks.check(f"planned {key} count {want}", got == want, f"got {got}")

    print()
    print("2. real-chunk scenes (single chunk, walls on the sides)")
    scenes = fixture_scenes()
    stats: Dict[str, Dict[str, int]] = {}
    lit: Dict[str, Tuple[np.ndarray, np.ndarray]] = {}
    for name, (volume, _info) in scenes.items():
        t0 = time.perf_counter()
        sky, block = relight_reference(volume, opacity_table, emitter_ids,
                                       emitter_levels, True)
        elapsed = time.perf_counter() - t0
        stat = light_statistics(sky, block)
        stats[name] = stat
        lit[name] = (sky, block)
        print(f"  {name:18s} {elapsed:5.1f}s  "
              f"sky_lit {stat['sky_lit']:6d}  middle {stat['sky_middle']:5d}  "
              f"block_lit {stat['block_lit']:4d}  any_lit {stat['any_lit']:6d}")

    base_stat = stats["base"]
    shaft_stat = stats["shafts"]
    no_flood = light_statistics(column_fill_reference(scenes["shafts"][0],
                                                      opacity_table),
                                np.zeros((SECTIONS, CELLS_PER_SECTION), np.uint8))
    print(f"  {'shafts, stage 1 only':18s}        "
          f"sky_lit {no_flood['sky_lit']:6d}  middle {no_flood['sky_middle']:5d}  "
          f"at 15 {no_flood['sky_full']:6d}")

    tolerance = 0.01
    checks.check("base (no shaft) is this oracle's pinned column",
                 abs(base_stat["sky_lit"] - ORACLE_BASE_LIT) <= ORACLE_BASE_LIT * tolerance
                 and abs(base_stat["sky_middle"] - ORACLE_BASE_MIDDLE) <= 4,
                 f"got {base_stat['sky_lit']}/{base_stat['sky_middle']} "
                 f"pinned {ORACLE_BASE_LIT}/{ORACLE_BASE_MIDDLE}")
    checks.check("shafted column reproduces section 5.2's engine row",
                 abs(shaft_stat["sky_lit"] - PLAN_ENGINE_LIT) <= PLAN_ENGINE_LIT * tolerance
                 and abs(shaft_stat["sky_middle"] - PLAN_ENGINE_MIDDLE)
                 <= max(8, PLAN_ENGINE_MIDDLE // 20),
                 f"got {shaft_stat['sky_lit']}/{shaft_stat['sky_middle']} vs plan "
                 f"{PLAN_ENGINE_LIT}/{PLAN_ENGINE_MIDDLE}")
    checks.check("stage 1 alone reproduces section 5.2's no-flood-fill row",
                 abs(no_flood["sky_full"] - PLAN_NO_FLOOD_LIT) <= 8
                 and abs(no_flood["sky_middle"] - PLAN_NO_FLOOD_MIDDLE) <= 4,
                 f"got {no_flood['sky_full']} at 15 and {no_flood['sky_middle']} "
                 f"middle vs plan {PLAN_NO_FLOOD_LIT}/{PLAN_NO_FLOOD_MIDDLE}")

    for name in ("base", "shafts"):
        t0 = time.perf_counter()
        relaxed_sky, relaxed_block = max_field_reference(
            scenes[name][0], opacity_table, emitter_ids, emitter_levels, True)
        sky_diff = int((relaxed_sky != lit[name][0]).sum())
        block_diff = int((relaxed_block != lit[name][1]).sum())
        checks.check(f"BFS == max-field relaxation ({name})",
                     sky_diff == 0 and block_diff == 0,
                     f"sky {sky_diff}, block {block_diff} cells differ "
                     f"({time.perf_counter() - t0:.1f}s)")

    print("  attribution: section 5.2's 66,082/694 is the shafted column, not the "
          "unshafted one:")
    print(f"    unshafted      {base_stat['sky_lit']:6d} lit / "
          f"{base_stat['sky_middle']:4d} middle   (plan 5.2 does not list it)")
    print(f"    shafted        {shaft_stat['sky_lit']:6d} lit / "
          f"{shaft_stat['sky_middle']:4d} middle   (plan {PLAN_ENGINE_LIT} / "
          f"{PLAN_ENGINE_MIDDLE}, {shaft_stat['sky_lit'] - PLAN_ENGINE_LIT:+d} / "
          f"{shaft_stat['sky_middle'] - PLAN_ENGINE_MIDDLE:+d})")
    print(f"    stage 1 only   {no_flood['sky_lit']:6d} lit / "
          f"{no_flood['sky_middle']:4d} middle   (plan {PLAN_NO_FLOOD_LIT} / "
          f"{PLAN_NO_FLOOD_MIDDLE}; at 15: {no_flood['sky_full']} vs "
          f"{PLAN_NO_FLOOD_LIT})")

    cave_sky, cave_block = lit["sealed_cave_torch"]
    room = scenes["sealed_cave_torch"][1]
    if room:
        room_cells = [chunk_cell(x, y, z)
                      for y in range(room["y0"], room["y1"] + 1)
                      for z in range(room["z0"], room["z1"] + 1)
                      for x in range(room["x0"], room["x1"] + 1)]
        room_sky = np.asarray(cave_sky, dtype=np.uint8).reshape(-1)[room_cells]
        room_block = np.asarray(cave_block, dtype=np.uint8).reshape(-1)[room_cells]
        checks.check("sealed cave has no sky light", int(room_sky.max()) == 0,
                     f"max {int(room_sky.max())}")
        at_torch = int(cave_block.reshape(-1)[
            chunk_cell(room["torch_x"], room["torch_y"], room["torch_z"])])
        checks.check("sealed cave torch holds its luminance 14", at_torch == 14,
                     f"got {at_torch}")
        checks.check("sealed cave torch lights the room and falls off to 0",
                     int(room_block.max()) > 0 and int(room_block.min()) == 0,
                     f"min {int(room_block.min())} max {int(room_block.max())}")

    column_sky, _column_block = lit["water_column"]
    column = scenes["water_column"][1]
    if column:
        flat = np.asarray(column_sky, dtype=np.uint8).reshape(-1)
        got = [int(flat[chunk_cell(column["x"], column["top"] - (n - 1),
                                   column["z"])])
               for n in range(1, column["depth"] + 1)]
        want = [15 - n for n in range(1, column["depth"] + 1)]
        checks.check("fixture water column: 15 - n under its surface", got == want,
                     f"got {got} want {want}")

    _semantic_checks(checks, opacity_table, emitter_ids, emitter_levels)
    _incremental_checks(checks, base, opacity_table, emitter_ids, emitter_levels)
    _boundary_check(checks, base, opacity_table, emitter_ids, emitter_levels)

    print()
    print(f"RESULT: {'PASS' if checks.failed == 0 else 'FAIL'} "
          f"({checks.passed}/{checks.passed + checks.failed}) "
          f"in {time.perf_counter() - started:.1f}s")
    return 0 if checks.failed == 0 else 1


