# --------------------------------------------------------------------------
# geometry: the overworld window (main world: min_y -64, height 384)
# --------------------------------------------------------------------------

MIN_Y = -64
HEIGHT = 384
SECTIONS = HEIGHT // 16          # 24
CELLS_PER_SECTION = 4096
CELLS_PER_CHUNK = HEIGHT * 256   # 98_304, flat index (y - MIN_Y)*256 + z*16 + x
MAX_Y = MIN_Y + HEIGHT           # 320, exclusive

AIR = 0


def chunk_cell(x: int, y: int, z: int) -> int:
    """Flat index of `(x, y, z)` in a `(24, 4096)` chunk volume."""
    return (y - MIN_Y) * 256 + z * 16 + x


def chunk_coords(index: int) -> Tuple[int, int, int]:
    """Inverse of `chunk_cell`: flat index -> `(x, y, z)`."""
    return index % 16, MIN_Y + index // 256, (index // 16) % 16


def get_state(volume: np.ndarray, x: int, y: int, z: int) -> int:
    """Block state id at world `(x, y, z)` of one chunk's `(24, 4096)` volume."""
    return int(volume.reshape(-1)[chunk_cell(x, y, z)])


def set_state(volume: np.ndarray, x: int, y: int, z: int, state: int) -> None:
    """Write a block state id into one chunk's `(24, 4096)` volume, in place."""
    volume.reshape(-1)[chunk_cell(x, y, z)] = state


def column_top(volume: np.ndarray, x: int, z: int) -> int:
    """Highest non-air world Y in a column, or `MIN_Y - 1` if it is all air.

    Vanilla's `HeightMap.WorldSurface` predicate is "not air", and stage 2 of
    the sky light seeds off exactly this number, so a flower counts and water
    counts. Nothing here uses a heightmap's `+2` convention (section 5.4).
    """
    flat = volume.reshape(-1)
    for y in range(MAX_Y - 1, MIN_Y - 1, -1):
        if flat[chunk_cell(x, y, z)] != AIR:
            return y
    return MIN_Y - 1


# --------------------------------------------------------------------------
# region buffers: the 3x3 chunk neighbourhood, flat, with a 1-cell wall
# --------------------------------------------------------------------------
#
# Layout `(y, z, x)` over 48 x 388 x 50 with one wall cell on each side, so a
# step in any direction is a constant offset and a step off the region lands in
# a cell that is permanently opacity 15 / light 0 -- the same result as
# "no such neighbour", without a bounds check per step.

_PAD = 1
_SPAN = 48 + 2 * _PAD             # 50
_PLANE = _SPAN * _SPAN            # 2500
_Y_PAD = 2
_REGION_Y = HEIGHT + 2 * _Y_PAD   # 388
_REGION_CELLS = _REGION_Y * _PLANE

_STEP_X = 1
_STEP_Z = _SPAN
_STEP_Y = _PLANE
_DOWN = -_STEP_Y
_DIRECTIONS = (-_STEP_X, _STEP_X, -_STEP_Z, _STEP_Z, -_STEP_Y, _STEP_Y)
_REGION_SIDE = 48                 # region columns per axis, before the wall


def _chunk_index(dx: int, dz: int) -> int:
    """3x3 chunk index: `(dz+1)*3 + (dx+1)` (LIGHT_PLAN section 3)."""
    return (dz + 1) * 3 + (dx + 1)


def chunk_index(dx: int, dz: int) -> int:
    """Public alias of the region layout's chunk index, for callers."""
    return _chunk_index(dx, dz)


def _region_origin(dx: int, dz: int) -> Tuple[int, int]:
    """Region-local column origin of chunk `(dx, dz)`.

    The region's 48 columns run west to east, north to south: chunk `(-1,-1)`
    owns 0..15, the centre chunk 16..31, `(1,1)` 32..47. Light has to be able
    to cross a border, so the centre is never at the region's own origin.
    """
    return 16 * (dx + 1), 16 * (dz + 1)


_CENTER_CHUNK = _chunk_index(0, 0)
_CENTER_VALID = np.zeros(9, dtype=bool)
_CENTER_VALID[_CENTER_CHUNK] = True


def _padded(wx: int, wy: int, wz: int) -> int:
    """Flat index of a region column/cell. `wx`, `wz` are region-local 0..47."""
    return (wy - MIN_Y + _Y_PAD) * _PLANE + (wz + _PAD) * _SPAN + (wx + _PAD)


def _local_padded(x: int, y: int, z: int) -> int:
    """Flat index of a cell named in the centre chunk's own `(x, z)`."""
    wx, wz = _region_origin(0, 0)
    return _padded(wx + x, y, wz + z)


def _load_region(
    blocks_region: np.ndarray,
    opacity_table: np.ndarray,
    valid: np.ndarray,
) -> Tuple[bytearray, bytearray]:
    """Build the opacity and non-air buffers for a 3x3 region.

    Absent chunks (and the wall) keep opacity 15 and count as non-air, so they
    stop light exactly like an unloaded chunk would.
    """
    table = np.asarray(opacity_table, dtype=np.uint8)
    if table.size < 65536:
        raise ValueError(f"opacity_table must hold 65536 states, got {table.size}")
    op_np = np.full((_REGION_Y, _SPAN, _SPAN), 15, dtype=np.uint8)
    nonair_np = np.ones((_REGION_Y, _SPAN, _SPAN), dtype=np.uint8)
    for ci in range(9):
        if not valid[ci]:
            continue
        dx, dz = ci % 3 - 1, ci // 3 - 1
        states = np.asarray(blocks_region[ci], dtype=np.uint16).reshape(SECTIONS, 16, 16, 16)
        wx, wz = _region_origin(dx, dz)
        ox, oz = _PAD + wx, _PAD + wz
        box = (slice(_Y_PAD, _Y_PAD + HEIGHT), slice(oz, oz + 16), slice(ox, ox + 16))
        op_np[box] = table[states].reshape(HEIGHT, 16, 16)
        nonair_np[box] = (states != AIR).reshape(HEIGHT, 16, 16)
    return bytearray(op_np.tobytes()), bytearray(nonair_np.tobytes())


def _load_light(light_vol: np.ndarray, dx: int = 0, dz: int = 0) -> bytearray:
    """Copy a `(24, 4096)` light volume into a region buffer (other chunks 0)."""
    out = bytearray(_REGION_CELLS)
    view = np.frombuffer(out, dtype=np.uint8).reshape(_REGION_Y, _SPAN, _SPAN)
    wx, wz = _region_origin(dx, dz)
    ox, oz = _PAD + wx, _PAD + wz
    view[_Y_PAD:_Y_PAD + HEIGHT, oz:oz + 16, ox:ox + 16] = np.asarray(
        light_vol, dtype=np.uint8).reshape(HEIGHT, 16, 16)
    return out


def _extract_chunk(region_buffer: bytearray, dx: int = 0, dz: int = 0) -> np.ndarray:
    """One chunk out of a region buffer, as a `(24, 4096)` array."""
    view = np.frombuffer(bytes(region_buffer), dtype=np.uint8).reshape(
        _REGION_Y, _SPAN, _SPAN)
    wx, wz = _region_origin(dx, dz)
    ox, oz = _PAD + wx, _PAD + wz
    chunk = view[_Y_PAD:_Y_PAD + HEIGHT, oz:oz + 16, ox:ox + 16]
    return chunk.reshape(SECTIONS, CELLS_PER_SECTION).copy()


def _region_tops(nonair: bytearray, valid: np.ndarray) -> List[int]:
    """Highest non-air world Y per region column, indexed `wz*48 + wx`.

    Columns of absent chunks (and the wall) keep `MIN_Y - 1`, i.e. they carry
    no height signal. For the cell that is being seeded that is the same answer
    as Pumpkin's "use the column's own top when the neighbour is out of range":
    a neighbour height can only add a seed `y < neighbour_top`, and a cell with
    light already has `y >= own top >= MIN_Y - 1`.
    """
    tops = [MIN_Y - 1] * (_REGION_SIDE * _REGION_SIDE)
    for ci in range(9):
        if not valid[ci]:
            continue
        dx, dz = ci % 3 - 1, ci // 3 - 1
        wx0, wz0 = _region_origin(dx, dz)
        for lz in range(16):
            wz = wz0 + lz
            row = wz * _REGION_SIDE
            for lx in range(16):
                wx = wx0 + lx
                idx = _padded(wx, MAX_Y - 1, wz)
                for py in range(HEIGHT - 1, -1, -1):
                    if nonair[idx]:
                        tops[row + wx] = MIN_Y + py
                        break
                    idx -= _STEP_Y
    return tops


# --------------------------------------------------------------------------
# the three sky stages and the increase BFS
# --------------------------------------------------------------------------


def _sky_fill(sky: bytearray, op: bytearray, tops: List[int], valid: np.ndarray) -> None:
    """Stage 1: the light a column has from its own column alone."""
    for ci in range(9):
        if not valid[ci]:
            continue
        dx, dz = ci % 3 - 1, ci // 3 - 1
        wx0, wz0 = _region_origin(dx, dz)
        for lz in range(16):
            wz = wz0 + lz
            for lx in range(16):
                wx = wx0 + lx
                top = tops[wz * _REGION_SIDE + wx]
                base = _padded(wx, MIN_Y, wz)

                # Everything above the highest non-air block is in daylight.
                up = base + (top - MIN_Y + 1) * _STEP_Y
                for _ in range(HEIGHT - 1 - (top - MIN_Y)):
                    sky[up] = 15
                    up += _STEP_Y

                # Down from that block: `light -= opacity`, saturating, stop at
                # 0. No `max(opacity, 1)` and no down special here -- section
                # 4.3 is explicit that both belong to the BFS instead.
                light = 15
                idx = base + (top - MIN_Y) * _STEP_Y
                for _ in range(top - MIN_Y + 1):
                    light -= op[idx]
                    if light < 0:
                        light = 0
                    sky[idx] = light
                    if light == 0:
                        break
                    idx -= _STEP_Y


def _sky_seed(sky: bytearray, tops: List[int], valid: np.ndarray, queue: deque) -> None:
    """Stage 2: lateral seeds at the surface and below every neighbour's top."""
    for ci in range(9):
        if not valid[ci]:
            continue
        dx, dz = ci % 3 - 1, ci // 3 - 1
        wx0, wz0 = _region_origin(dx, dz)
        for lz in range(16):
            wz = wz0 + lz
            row = wz * _REGION_SIDE
            for lx in range(16):
                wx = wx0 + lx
                top = tops[row + wx]
                n_top = tops[row - _REGION_SIDE + wx] if wz > 0 else MIN_Y - 1
                s_top = (tops[row + _REGION_SIDE + wx]
                         if wz + 1 < _REGION_SIDE else MIN_Y - 1)
                w_top = tops[row + wx - 1] if wx > 0 else MIN_Y - 1
                e_top = (tops[row + wx + 1]
                         if wx + 1 < _REGION_SIDE else MIN_Y - 1)
                max_check = max(top, n_top, s_top, w_top, e_top)

                idx = _padded(wx, max_check, wz)
                for wy in range(max_check, MIN_Y - 1, -1):
                    level = sky[idx]
                    if level == 0:
                        if wy <= top:
                            break
                    elif (wy == top or wy < n_top or wy < s_top
                          or wy < w_top or wy < e_top):
                        queue.append(idx)
                    idx -= _STEP_Y


def _block_seed(
    block: bytearray,
    blocks_region: np.ndarray,
    lum_table: np.ndarray,
    valid: np.ndarray,
    queue: deque,
) -> None:
    """Block light stage 1: every emitting cell becomes a seed."""
    for ci in range(9):
        if not valid[ci]:
            continue
        dx, dz = ci % 3 - 1, ci // 3 - 1
        wx0, wz0 = _region_origin(dx, dz)
        states = np.asarray(blocks_region[ci], dtype=np.uint16).reshape(SECTIONS, 16, 16, 16)
        for s, ly, lz, lx in np.argwhere(lum_table[states] > 0):
            level = int(lum_table[states[s, ly, lz, lx]])
            idx = _padded(wx0 + int(lx), MIN_Y + 16 * int(s) + int(ly), wz0 + int(lz))
            block[idx] = level
            queue.append(idx)


def _increase(light: bytearray, op: bytearray, queue: deque, is_sky: bool) -> None:
    """Stages 3 of both engines: propagate, re-queueing whenever a cell rises.

    `new_level = level - max(opacity, 1)`, plus the sky's down special. There is
    no visited set, so a cell can be re-queued from a brighter path; the value
    written is then the maximum over paths and the result is order independent.
    """
    while queue:
        idx = queue.popleft()
        level = light[idx]
        if level <= 1:
            continue
        for delta in _DIRECTIONS:
            n = idx + delta
            nop = op[n]
            if nop == 0 and is_sky and level == 15 and delta == _DOWN:
                new = 15
            elif nop <= 1:
                new = level - 1
            else:
                new = level - nop
            if new > light[n]:
                light[n] = new
                if new > 1:
                    queue.append(n)


def _decrease(
    light: bytearray,
    op: bytearray,
    seeds: Iterable[Tuple[int, int]],
    is_sky: bool,
    increase: deque,
) -> None:
    """Vanilla's decrease, over region indices.

    `seeds` are `(region_index, old_level)` and must already be cleared to 0
    (section 9.1 pit 2). The vanilla judgement is
    `neighbour == old - max(op, 1) || neighbour < old -> clear and continue`;
    anything brighter is handed to the increase pass. The sky version carries
    the same down special as the increase, which is what stops a removed block
    above a water surface from clearing the whole column.
    """
    queue = deque(seeds)
    while queue:
        idx, old = queue.popleft()
        for delta in _DIRECTIONS:
            n = idx + delta
            nlevel = light[n]
            if nlevel == 0:
                continue
            nop = op[n]
            if nop == 0 and is_sky and old == 15 and delta == _DOWN:
                predicted = 15
            elif nop <= 1:
                predicted = old - 1
            else:
                predicted = old - nop
            if predicted < 0:
                predicted = 0
            if nlevel == predicted or nlevel < old:
                light[n] = 0
                queue.append((n, nlevel))
            else:
                increase.append(n)


def region_surfaces(
    blocks_region: np.ndarray,
    valid: Optional[Sequence[bool]] = None,
) -> np.ndarray:
    """The `surfaces (48, 48) int32` array the kernel's signature takes.

    `surfaces[wz][wx]` is the highest **non-air** block's world Y for that
    column of the 3x3 region; a column of an absent chunk reads `MIN_Y - 1`.
    Row 16 is the centre chunk's own first row (`wz == 16`), column 16 its first
    column -- the same region-local order `relight_reference_region` uses.

    This is Pumpkin's `HeightMap::WorldSurface`, the definition
    `LIGHT_PLAN.md` section 4.3 states (leaves, flowers and a torch count, water
    counts). `region_blocking_tops` is the other definition, and the two differ
    exactly in a column whose highest non-air block is transparent.
    """
    region = np.asarray(blocks_region, dtype=np.uint16).reshape(
        9, SECTIONS, CELLS_PER_SECTION)
    mask = np.ones(9, dtype=bool) if valid is None else np.asarray(valid, dtype=bool)
    _op, nonair = _load_region(region, np.full(65536, 15, dtype=np.uint8), mask)
    tops = _region_tops(nonair, mask)
    return np.asarray(tops, dtype=np.int32).reshape(_REGION_SIDE, _REGION_SIDE)


def region_blocking_tops(
    blocks_region: np.ndarray,
    opacity_table: np.ndarray,
    valid: Optional[Sequence[bool]] = None,
) -> np.ndarray:
    """Highest cell with `opacity > 0` per region column, as region-relative ry.

    This is vanilla's `Heightmap.Types.LIGHT_BLOCKING`, which is what
    `ChunkSkyLightSources` scans a column with, and what `world/light_engine.py`'s
    own `_column_top` computes. `-1` means the column has no cell with
    `opacity > 0` at all (an all-air or all-glass column).

    Why both exist: `region_surfaces` is the *non-air* top of section 4.3 and is
    what the oracle's stage-2 seeds use; the kernel uses this one. On every scene
    measured so far the two produce cell-for-cell identical light fields
    (`tools/check_light_engine.py` asserts both facts separately), but they are
    different rules and only this one can be compared to the kernel's own.
    """
    region = np.asarray(blocks_region, dtype=np.uint16).reshape(
        9, SECTIONS, CELLS_PER_SECTION)
    mask = np.ones(9, dtype=bool) if valid is None else np.asarray(valid, dtype=bool)
    op, _nonair = _load_region(region, opacity_table, mask)
    tops = np.full((_REGION_SIDE, _REGION_SIDE), -1, dtype=np.int32)
    for ci in range(9):
        if not mask[ci]:
            continue
        dx, dz = ci % 3 - 1, ci // 3 - 1
        wx0, wz0 = _region_origin(dx, dz)
        for lz in range(16):
            wz = wz0 + lz
            for lx in range(16):
                wx = wx0 + lx
                idx = _padded(wx, MAX_Y - 1, wz)
                for py in range(HEIGHT - 1, -1, -1):
                    if op[idx] > 0:
                        tops[wz, wx] = py
                        break
                    idx -= _STEP_Y
    return tops


