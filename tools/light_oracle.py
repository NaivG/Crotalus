def _registry_blocks():
    from registry import init_registries
    return init_registries(log_summary=False).blocks


def registry_opacity_table() -> np.ndarray:
    """Global state id -> opacity, `uint8[65536]`, from `BlockType.opacity`.

    Built from `registry/entries.py`'s per-state accessor on purpose: the
    engine is fed `registry.blocks.light_opacity_table()`, and the oracle must
    not inherit a mistake made while building that one. The plan's three values
    (0 / 1 / 15) and "never use `state_flags`" are section 1.1.
    """
    table = np.zeros(65536, dtype=np.uint8)
    registry = _registry_blocks()
    for name in registry:
        block = registry.blocks[name]
        lo = block.first_state_id
        table[lo:lo + block.state_count] = np.asarray(block.opacity, dtype=np.uint8)
    return table


def registry_emitter_tables() -> Tuple[np.ndarray, np.ndarray]:
    """`(state ids, luminance)` for every emitting state, ascending by state id."""
    ids: List[int] = []
    levels: List[int] = []
    registry = _registry_blocks()
    for name in registry:
        block = registry.blocks[name]
        for offset, luminance in enumerate(block.luminance):
            if luminance > 0:
                ids.append(block.first_state_id + offset)
                levels.append(int(luminance))
    return np.asarray(ids, dtype=np.int32), np.asarray(levels, dtype=np.uint8)


def emitter_lum_table(emitter_ids, emitter_levels) -> np.ndarray:
    """Public form of the luminance table, for callers that hold the pairs."""
    return _emitter_lum_table(emitter_ids, emitter_levels)


