class _Checks:
    """Collect failures instead of raising on the first one (repo style)."""

    def __init__(self) -> None:
        self.passed = 0
        self.failed = 0

    def check(self, name: str, ok: bool, detail: str = "") -> bool:
        if ok:
            self.passed += 1
        else:
            self.failed += 1
        suffix = f"  {detail}" if detail else ""
        print(f"  [{'ok' if ok else 'FAIL'}] {name}{suffix}")
        return ok


