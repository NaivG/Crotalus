def _incremental_checks(checks: _Checks, volume, opacity_table,
                        emitter_ids, emitter_levels) -> None:
    """Section 7.1 item 6: the incremental path must equal a full relight."""
    print()
    print("4. increment == full relight (the section 7.1 item 6 assertion)")
    sky, block = relight_reference(volume, opacity_table, emitter_ids,
                                   emitter_levels, True)

    stone = _stone()
    torch = _state("minecraft:torch")
    changes = [(8, 100, 8, stone), (4, -20, 12, stone), (2, -30, 2, AIR),
               (12, -45, 3, torch)]
    edited = volume.copy()
    applied = []
    for x, y, z, state in changes:
        old = get_state(edited, x, y, z)
        if old == state:
            continue
        set_state(edited, x, y, z, state)
        applied.append((x, y, z, old, state))

    inc_sky, inc_block = incremental_reference(
        sky, block, volume, edited, opacity_table, emitter_ids, emitter_levels, True)
    full_sky, full_block = relight_reference(edited, opacity_table,
                                             emitter_ids, emitter_levels, True)

    sky_diff = int((inc_sky != full_sky).sum())
    block_diff = int((inc_block != full_block).sum())
    checks.check("incremental sky == full sky", sky_diff == 0, f"{sky_diff} cells differ")
    checks.check("incremental block light == full block light",
                 block_diff == 0, f"{block_diff} cells differ")
    for x, y, z, old, state in applied:
        index = chunk_cell(x, y, z)
        print(f"    change ({x},{y},{z}) {old} -> {state}: "
              f"sky {sky.reshape(-1)[index]} -> {inc_sky.reshape(-1)[index]} "
              f"(full {full_sky.reshape(-1)[index]}), "
              f"block {block.reshape(-1)[index]} -> {inc_block.reshape(-1)[index]} "
              f"(full {full_block.reshape(-1)[index]})")


def _boundary_check(checks: _Checks, volume, opacity_table, emitter_ids,
                    emitter_levels) -> None:
    """A 3x3 region must let a neighbour's light cross the chunk border."""
    print()
    print("5. 3x3 region: light crosses a chunk border")
    centre = np.zeros_like(volume)          # all air, so the border is open
    west = volume.copy()
    set_state(west, 15, -30, 8, _state("minecraft:torch"))
    region = np.zeros((9, SECTIONS, CELLS_PER_SECTION), dtype=np.uint16)
    region[_chunk_index(0, 0)] = centre
    region[_chunk_index(-1, 0)] = west
    valid = np.zeros(9, dtype=bool)
    valid[_chunk_index(0, 0)] = True
    valid[_chunk_index(-1, 0)] = True
    _sky, block = relight_reference_region(region, opacity_table, emitter_ids,
                                           emitter_levels, True, valid)
    near = int(block[_chunk_index(0, 0)].reshape(-1)[chunk_cell(0, -30, 8)])
    checks.check("a torch one block across the border lights the centre chunk",
                 near == 13, f"got {near}")

    _closed_sky, closed_block = relight_reference(
        centre, opacity_table, emitter_ids, emitter_levels, True)
    single = int(closed_block.reshape(-1)[chunk_cell(0, -30, 8)])
    checks.check("with no neighbour the same cell has no block light",
                 single == 0, f"got {single}")

    # Sky light across the border, and the only case where a neighbour's
    # *height* matters: the centre chunk is a covered shaft whose own column
    # never seeds it, so the light has to arrive sideways from the neighbour's
    # open sky. A region loaded with the wrong chunk origins cannot do this.
    west = np.zeros_like(volume)
    _fill_box(west, 0, MIN_Y, 0, 15, -26, 15, _stone())        # top at -26
    centre = np.zeros_like(volume)
    _fill_box(centre, 0, MIN_Y, 0, 15, -20, 15, _stone())      # top at -20
    for y in range(-30, -20):
        set_state(centre, 0, y, 8, AIR)                        # shaft, roofed

    sky, _block = relight_reference(centre, opacity_table, emitter_ids,
                                    emitter_levels, True,
                                    neighbours={(-1, 0): west})
    got = int(sky.reshape(-1)[chunk_cell(0, -25, 8)])
    checks.check("neighbour's surface light crosses into a roofed shaft",
                 got == 14, f"got {got}")

    _closed_sky, _closed_block = relight_reference(
        centre, opacity_table, emitter_ids, emitter_levels, True)
    sealed = int(_closed_sky.reshape(-1)[chunk_cell(0, -25, 8)])
    checks.check("the same shaft is dark with no neighbour", sealed == 0,
                 f"got {sealed}")

    region[_chunk_index(0, 0)] = centre
    region[_chunk_index(-1, 0)] = west
    region_sky, _region_block = relight_reference_region(
        region, opacity_table, emitter_ids, emitter_levels, True, valid)
    same = bool((region_sky[_chunk_index(0, 0)] == sky).all())
    checks.check("neighbours= and the 3x3 region API agree on the centre", same)


